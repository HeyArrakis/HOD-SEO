def write(name, cols, rows):
    path = os.path.join(OUT, name)
    for r in rows:
        assert len(r) == len(cols), (name, r[0], len(r))
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, quoting=csv.QUOTE_MINIMAL)
        w.writerow(cols)
        w.writerows(rows)
    print(f"{name}: {len(rows)} rows")


